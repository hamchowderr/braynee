'use strict';
// ci-workflow-core.js — pure helpers behind gen-ci-workflow.mjs (cp-asf).
// Detect a repo's toolchain and compose a GitHub Actions workflow that runs REAL
// lint+typecheck+test, so the autonomous-ship gh:run gate can never go "vacuously
// green" (a passing gate with no actual checks). Kept CommonJS + side-effect-free
// (except detectStack reading the repo) so it's unit-testable.

const fs = require('fs');
const path = require('path');

// How you invoke a package.json script under each package manager.
function scriptCmd(pm, name) {
  return pm === 'npm' ? `npm run ${name}` : `${pm} ${name}`;
}

// Inspect a repo dir → { pm, install, lint, typecheck, test } (each cmd or null).
function detectStack(repoDir) {
  const exists = (f) => { try { return fs.existsSync(path.join(repoDir, f)); } catch { return false; } };
  let pkg = {};
  try { pkg = JSON.parse(fs.readFileSync(path.join(repoDir, 'package.json'), 'utf8')); } catch {}
  const scripts = pkg.scripts || {};

  const pm = exists('pnpm-lock.yaml') ? 'pnpm' : exists('yarn.lock') ? 'yarn' : 'npm';
  const install = pm === 'pnpm' ? 'pnpm install --frozen-lockfile'
    : pm === 'yarn' ? 'yarn install --frozen-lockfile'
    : 'npm ci';

  // Prefer an explicit package.json script; else fall back to a detected tool.
  let lint = null;
  if (scripts.lint) lint = scriptCmd(pm, 'lint');
  else if (exists('biome.json') || exists('biome.jsonc')) lint = 'npx --yes @biomejs/biome check .';
  else if (['.eslintrc', '.eslintrc.json', '.eslintrc.cjs', '.eslintrc.js', 'eslint.config.js', 'eslint.config.mjs'].some(exists))
    lint = 'npx --yes eslint .';

  let typecheck = null;
  if (scripts.typecheck) typecheck = scriptCmd(pm, 'typecheck');
  else if (exists('tsconfig.json')) typecheck = 'npx --yes tsc --noEmit';

  let test = null;
  if (scripts.test) test = scriptCmd(pm, 'test');

  return { pm, install, lint, typecheck, test };
}

// Compose the workflow YAML from a detected stack.
// `name` is the on-disk workflow file name (default ci.yml); the workflow's display
// name is "CI" — deliberately NOT "Claude Code Review" (that advisory workflow is
// excluded from the gate, so the generated one must be distinct to count).
function composeWorkflow(stack, branch = 'main') {
  const steps = [];
  if (stack.lint) steps.push({ name: 'Lint', run: stack.lint });
  if (stack.typecheck) steps.push({ name: 'Typecheck', run: stack.typecheck });
  if (stack.test) steps.push({ name: 'Test', run: stack.test });

  // No-vacuous-green guard: if nothing real was detected, author a step that FAILS
  // so the gate goes red instead of passing with zero checks.
  if (steps.length === 0) {
    steps.push({
      name: 'No real checks detected',
      run: 'echo "No lint/typecheck/test detected — add real checks before this gate can pass." && exit 1',
    });
  }

  const yamlSteps = steps.map(s =>
    `      - name: ${s.name}\n        run: ${s.run}`).join('\n');

  return `# Generated by braynee gen-ci-workflow (cp-asf) — runs real lint+typecheck+test.
# Named "CI" on purpose: the advisory "Claude Code Review" workflow is excluded from
# the autonomous-ship gh:run gate, so this must be a distinct, substantive workflow.
name: CI

on:
  pull_request:
  push:
    branches: [${branch}]

jobs:
  ci:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 20
      - name: Install
        run: ${stack.install}
${yamlSteps}
`;
}

// True when the gh:run gate should IGNORE this workflow name (the advisory reviewer).
function isAdvisoryWorkflow(nameOrFile) {
  return /claude[\s_-]*code[\s_-]*review/i.test(String(nameOrFile || ''));
}

module.exports = { scriptCmd, detectStack, composeWorkflow, isAdvisoryWorkflow };
