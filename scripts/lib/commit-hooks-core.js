'use strict';

// commit-hooks-core.js — pure helpers behind install-commit-hooks.mjs (cp-lj73.3).
//
// The git-side half of the commit/PR conventions: the Claude-side guard
// (cp-lj73.2) only sees commits the AGENT makes, so a human committing by hand,
// a teammate, or any other tool bypasses it entirely. commitlint on the
// commit-msg hook closes that, for every committer in the clone.
//
// The STANDARD is not defined here either. It is authored once in
// skills/setup/rules-templates/commit-pr-conventions.md (cp-lj73.1); the type
// list below is imported from hooks/lib/commit-format.js so the CI check, the
// Claude-side guard, and commitlint cannot disagree about what a valid type is.
//
// Side-effect-free except for the repo reads in planInstall(), so it is
// unit-testable without touching a real repo.

const fs = require('fs');
const path = require('path');

const { TYPES, RULE_PATH } = require(path.join(__dirname, '..', '..', 'hooks', 'lib', 'commit-format.js'));
const { detectStack } = require(path.join(__dirname, 'ci-workflow-core.js'));

// Versioned marker pair, mirroring how beads brackets its own managed section.
// Anything outside the markers is preserved verbatim on re-install — that is the
// entire reason this is a merge rather than a write.
const BEGIN = '# --- BEGIN BRAYNEE COMMIT-MSG LINT v1 ---';
const END = '# --- END BRAYNEE COMMIT-MSG LINT v1 ---';

/**
 * Coexistence with beads, verified against a real repo rather than assumed:
 *
 *   bd hooks install writes pre-commit, post-merge, pre-push, post-checkout and
 *   prepare-commit-msg. It does NOT write commit-msg — that shim is left bare.
 *
 * So commitlint takes commit-msg and nothing collides. The ordering is also the
 * useful one: git runs prepare-commit-msg BEFORE commit-msg, so beads' identity
 * trailer is already in the file that commitlint then validates — which is why
 * the config below must not reject a trailer-bearing message.
 */
const BEADS_OWNED_HOOKS = [
  'pre-commit', 'post-merge', 'pre-push', 'post-checkout', 'prepare-commit-msg',
];

/** The commitlint config. Type list comes from the single shared source. */
function commitlintConfig() {
  return `// Generated by braynee install-commit-hooks (cp-lj73.3).
// The written standard is ${RULE_PATH}; this file is the machine-checkable subset.
// The type list is generated from braynee's shared list, so the commit-msg hook,
// the Claude-side PreToolUse guard and the PR-title CI check cannot disagree.
module.exports = {
  extends: ['@commitlint/config-conventional'],
  rules: {
    'type-enum': [2, 'always', ${JSON.stringify(TYPES)}],
    // The rule's target is 50; config-conventional defaults to 100. Warn rather
    // than error: a 60-char subject is worth a nudge, not a rejected commit.
    'header-max-length': [1, 'always', 50],
    // beads' prepare-commit-msg hook appends identity trailers BEFORE commitlint
    // runs. Leaving these at error would fail commits for text the committer
    // never wrote.
    'footer-max-line-length': [0, 'always'],
    'body-max-line-length': [1, 'always', 100],
  },
};
`;
}

/** The husky/git commit-msg hook body that invokes commitlint. */
function commitlintHookSection() {
  return [
    BEGIN,
    '# Managed by braynee. Do not remove these markers — content between them is',
    '# replaced on re-install; anything outside is preserved.',
    '# --no-install: fail loudly if commitlint is not installed rather than',
    '# silently downloading it on every commit.',
    'npx --no -- commitlint --edit "$1"',
    END,
  ].join('\n');
}

/**
 * Dependency-free fallback for repos with no package.json, where commitlint
 * cannot run at all. Same grammar, enforced in POSIX sh.
 *
 * Deliberately mirrors the Claude-side guard's policy: reject only the
 * mechanical format failure. It skips merge/revert/fixup/squash messages, which
 * git generates itself and the committer cannot reword.
 */
function regexHookSection() {
  const types = TYPES.join('|');
  return [
    BEGIN,
    '# Managed by braynee. Do not remove these markers — content between them is',
    '# replaced on re-install; anything outside is preserved.',
    '# No package.json in this repo, so commitlint cannot run; same grammar in sh.',
    'braynee_msg=$(head -n 1 "$1")',
    '# git authors these itself — the committer cannot reword them.',
    'case "$braynee_msg" in',
    '  "Merge "*|"Revert "*|"fixup!"*|"squash!"*|"Reapply "*) exit 0 ;;',
    'esac',
    `if ! printf '%s' "$braynee_msg" | grep -Eq '^(${types})(\\([^)]+\\))?!?: .+'; then`,
    '  echo "COMMIT REJECTED: subject is not Conventional Commits form." >&2',
    '  echo "  got:      $braynee_msg" >&2',
    '  echo "  expected: type(scope): summary" >&2',
    `  echo "  types:    ${TYPES.join(', ')}" >&2`,
    `  echo "  standard: ${RULE_PATH}" >&2`,
    '  exit 1',
    'fi',
    END,
  ].join('\n');
}

/**
 * Splice a managed section into an existing hook, preserving everything else.
 *
 * Three cases, and the middle one is the point of the whole function: a repo
 * that already has a commit-msg hook (its own, or another tool's) must keep it.
 * Overwriting someone's hook to install a linter is not an acceptable trade.
 */
function mergeHookSection(existing, section) {
  const prev = String(existing || '');
  if (!prev.trim()) {
    return `#!/usr/bin/env sh\n${section}\n`;
  }
  const i = prev.indexOf(BEGIN);
  const j = prev.indexOf(END);
  if (i !== -1 && j !== -1 && j > i) {
    return prev.slice(0, i) + section + prev.slice(j + END.length);
  }
  const sep = prev.endsWith('\n') ? '' : '\n';
  return `${prev}${sep}\n${section}\n`;
}

/** True when this hook file already carries our managed section. */
function hasSection(content) {
  return String(content || '').includes(BEGIN);
}

/**
 * Where git will actually look for hooks in this repo.
 *
 * core.hooksPath must be honored, and a RELATIVE value resolved against the
 * repo — 26 of 50 repos on this machine redirect it (husky sets `.husky/_`), and
 * writing blindly to .git/hooks there produces a file git never runs.
 */
function gitHooksDir(repoDir, hooksPathValue) {
  const v = (hooksPathValue || '').trim();
  if (!v) return path.join(repoDir, '.git', 'hooks');
  return path.isAbsolute(v) ? v : path.join(repoDir, v);
}

/**
 * Decide what installing into this repo means, without writing anything.
 *
 * Returns { mode, files: [{path, contents, action}], deps, installCmd, notes }.
 * mode is one of:
 *   'husky'  — the repo already uses husky; add .husky/commit-msg (committed, so
 *              it travels to every teammate who runs install)
 *   'npm'    — the repo has package.json but no husky; add husky itself too
 *   'plain'  — no package.json, so commitlint cannot run: a dependency-free sh
 *              hook goes straight into git's hooks dir. Local-only by nature.
 */
function planInstall(repoDir, { hooksPath = '' } = {}) {
  const exists = (f) => { try { return fs.existsSync(path.join(repoDir, f)); } catch { return false; } };
  const read = (p) => { try { return fs.readFileSync(p, 'utf8'); } catch { return ''; } };

  const hasPkg = exists('package.json');
  const hasHusky = exists('.husky');
  const files = [];
  const notes = [];
  let deps = [];
  let installCmd = null;
  let mode;

  if (!hasPkg) {
    mode = 'plain';
    const dir = gitHooksDir(repoDir, hooksPath);
    const target = path.join(dir, 'commit-msg');
    const prev = read(target);
    files.push({
      path: target,
      contents: mergeHookSection(prev, regexHookSection()),
      action: hasSection(prev) ? 'update' : (prev.trim() ? 'merge' : 'create'),
      executable: true,
    });
    notes.push(
      'No package.json, so commitlint cannot run here — installed a dependency-free ' +
      'sh check with the same grammar. It lives in git\'s hooks dir, which is NOT ' +
      'committed, so each clone must install it separately.'
    );
  } else {
    mode = hasHusky ? 'husky' : 'npm';
    const stack = detectStack(repoDir);
    deps = ['@commitlint/cli', '@commitlint/config-conventional'];
    if (!hasHusky) deps.push('husky');
    installCmd = stack.pm === 'npm'
      ? `npm install --save-dev ${deps.join(' ')}`
      : `${stack.pm} add -D ${deps.join(' ')}`;

    const cfgName = ['commitlint.config.js', 'commitlint.config.cjs', 'commitlint.config.mjs',
      '.commitlintrc', '.commitlintrc.json', '.commitlintrc.js']
      .find((f) => exists(f));
    if (cfgName) {
      notes.push(`Left the existing ${cfgName} alone — a commitlint config already present is the repo's own choice.`);
    } else {
      files.push({
        path: path.join(repoDir, 'commitlint.config.cjs'),
        contents: commitlintConfig(),
        action: 'create',
      });
    }

    const target = path.join(repoDir, '.husky', 'commit-msg');
    const prev = read(target);
    files.push({
      path: target,
      contents: mergeHookSection(prev, commitlintHookSection()),
      action: hasSection(prev) ? 'update' : (prev.trim() ? 'merge' : 'create'),
      executable: true,
    });

    if (!hasHusky) {
      notes.push('Added husky. Run the install command, then `npx husky init` (or `npm run prepare`) once so git picks the hooks up.');
    }
    notes.push(
      'beads owns ' + BEADS_OWNED_HOOKS.join(', ') + ' — not commit-msg — so these ' +
      'coexist. prepare-commit-msg runs FIRST, so beads\' trailers are in the ' +
      'message commitlint validates; the generated config keeps footer length ' +
      'unrestricted for exactly that reason.'
    );
  }

  return { mode, files, deps, installCmd, notes };
}

/** package.json edits needed for the npm/husky modes: devDeps + prepare script. */
function planPackageJson(pkg, deps, { addPrepare }) {
  const next = JSON.parse(JSON.stringify(pkg || {}));
  const dev = next.devDependencies || (next.devDependencies = {});
  let changed = false;
  for (const d of deps) {
    if (!dev[d] && !(next.dependencies || {})[d]) { dev[d] = '*'; changed = true; }
  }
  if (addPrepare) {
    const scripts = next.scripts || (next.scripts = {});
    if (!scripts.prepare) { scripts.prepare = 'husky'; changed = true; }
  }
  return { pkg: next, changed };
}

module.exports = {
  BEGIN, END, TYPES, BEADS_OWNED_HOOKS,
  commitlintConfig, commitlintHookSection, regexHookSection,
  mergeHookSection, hasSection, gitHooksDir, planInstall, planPackageJson,
};
