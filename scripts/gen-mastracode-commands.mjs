#!/usr/bin/env node
// gen-mastracode-commands.mjs — generate Mastra Code slash commands from agents/.
//
// Why this exists (cp-3o3g.7 / cp-3o3g.4):
//   Claude Code loads agents/*.md as declarative subagents. Mastra Code cannot:
//   its subagent list comes from SDK config and a plugin cannot add to it, so
//   braynee's agents have no route there at all. The native path is the built-in
//   `subagent` tool, whose agentType is a fixed enum of explore/plan/execute.
//
//   These commands are that route. Each one asks the model to delegate to the
//   right built-in subagent type and to read the real braynee playbook first, so
//   the agent's actual instructions stay in agents/*.md and are never duplicated
//   here. Generated rather than hand-written so adding an agent cannot leave a
//   stale or missing command behind.
//
// Skills deliberately get NO generated command: Mastra Code already exposes them
// as /skill/<name> WITH arguments, so wrapping all 23 would be duplication with
// a sync burden and no gain.
//
// Usage:  node scripts/gen-mastracode-commands.mjs [--check]
//   --check  exit 1 if anything on disk is out of date (for CI / self-test)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const AGENTS_DIR = path.join(ROOT, 'agents');
const OUT_DIR = path.join(ROOT, 'commands', 'braynee');
const CHECK = process.argv.includes('--check');

const BANNER = 'GENERATED by scripts/gen-mastracode-commands.mjs — do not edit by hand.';

/** Minimal frontmatter reader: enough for `key: value` and folded `key: >` blocks. */
function readFrontmatter(source) {
  if (!source.startsWith('---')) return {};
  const end = source.indexOf('\n---', 3);
  if (end === -1) return {};
  // Split on \r?\n, not \n. Git checks these files out with CRLF on Windows, and
  // a trailing \r defeats the matcher below in a way that is easy to miss: in JS
  // `.` does not match \r (it is a line terminator) and `$` does not match before
  // one, so `key: value\r` silently fails to match and the field reads empty.
  //
  // The per-line strip is not redundant: the slice ends just before the closing
  // delimiter's \n, so the LAST frontmatter line keeps its \r and would be the
  // one field that silently vanishes.
  const lines = source
    .slice(3, end)
    .split(/\r?\n/)
    .map(line => line.replace(/\r$/, ''));

  const out = {};
  let key = null;
  let folded = [];

  const flush = () => {
    if (key && folded.length) out[key] = folded.join(' ').replace(/\s+/g, ' ').trim();
    folded = [];
  };

  for (const line of lines) {
    const m = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
    if (m && !/^\s/.test(line)) {
      flush();
      key = m[1];
      const value = m[2].trim();
      if (value === '>' || value === '|' || value === '') {
        folded = [];
      } else {
        out[key] = value;
        key = null;
      }
      continue;
    }
    if (key) folded.push(line.trim());
  }
  flush();
  return out;
}

/**
 * Which built-in subagent type fits this agent.
 *
 * Derived from the agent's own tool declaration rather than a hand-kept table,
 * so it cannot fall out of step: anything that can modify the workspace needs
 * `execute`; a read-only agent gets `explore`. No declaration means the agent
 * inherits every tool, which includes writes.
 */
function subagentTypeFor(frontmatter) {
  const tools = frontmatter.tools;
  if (!tools) return 'execute';
  return /\b(Write|Edit|NotebookEdit)\b/.test(tools) ? 'execute' : 'explore';
}

function firstSentence(text) {
  if (!text) return '';
  const m = /^(.*?[.!?])(\s|$)/.exec(text.trim());
  return (m ? m[1] : text.trim()).slice(0, 200);
}

function render({ name, description, agentType }) {
  const readOnly = agentType === 'explore';
  return `---
description: ${description || `Run braynee's ${name} agent.`}
---

<!-- ${BANNER} -->

Delegate this to braynee's **${name}** agent.

Call the \`subagent\` tool with:

- \`agentType\`: \`"${agentType}"\`${readOnly ? ' — this agent is read-only and must not modify the workspace.' : ''}
- \`task\`: a self-contained brief. A non-forked subagent cannot see this
  conversation, so restate everything it needs rather than referring back.

The brief must tell the subagent to first read braynee's playbook for this role
at \`agents/${name}.md\` inside the braynee plugin root — the braynee plugin
instructions give its absolute path — and then follow that playbook exactly. The
playbook is the source of truth for how this agent works; do not restate it here.

Request: $ARGUMENTS
`;
}

const agentFiles = fs
  .readdirSync(AGENTS_DIR, { withFileTypes: true })
  .filter(e => e.isFile() && e.name.endsWith('.md'))
  .map(e => e.name)
  .sort();

const expected = new Map();
for (const file of agentFiles) {
  const source = fs.readFileSync(path.join(AGENTS_DIR, file), 'utf8');
  const fm = readFrontmatter(source);
  const name = fm.name || path.basename(file, '.md');
  expected.set(`${name}.md`, render({
    name,
    description: firstSentence(fm.description),
    agentType: subagentTypeFor(fm),
  }));
}

fs.mkdirSync(OUT_DIR, { recursive: true });

const onDisk = fs.existsSync(OUT_DIR)
  ? fs.readdirSync(OUT_DIR).filter(f => f.endsWith('.md'))
  : [];

const stale = onDisk.filter(f => !expected.has(f));
const changed = [];

for (const [file, content] of expected) {
  const target = path.join(OUT_DIR, file);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (current !== content) {
    changed.push(file);
    if (!CHECK) fs.writeFileSync(target, content);
  }
}

if (!CHECK) for (const file of stale) fs.rmSync(path.join(OUT_DIR, file));

if (CHECK) {
  if (changed.length || stale.length) {
    console.error(
      `mastracode commands are out of date. Run: node scripts/gen-mastracode-commands.mjs\n` +
        (changed.length ? `  outdated: ${changed.join(', ')}\n` : '') +
        (stale.length ? `  orphaned: ${stale.join(', ')}\n` : ''),
    );
    process.exit(1);
  }
  console.log(`mastracode commands: up to date (${expected.size} commands)`);
} else {
  console.log(
    `mastracode commands: ${expected.size} generated` +
      (changed.length ? ` (${changed.length} written)` : ' (no changes)') +
      (stale.length ? `, ${stale.length} orphaned removed` : ''),
  );
}
